"""Keep the 6.12 release suffix consistent with the checked-out source."""
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import unittest

import yaml


ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts/read_kmi_generation.py"
BASH = os.environ.get("BAKASU_TEST_BASH", "bash")


class KmiGenerationTests(unittest.TestCase):
    def resolve(self, root):
        return subprocess.run([sys.executable, str(SCRIPT), str(root)],
                              capture_output=True, text=True)

    def test_reads_source_generation_instead_of_defaulting_to_five(self):
        for filename in ("build.config.constants", "build.config.common", "bazel/constants.scl"):
            for generation in (0, 5, 6, 7, 12):
                with self.subTest(file=filename, generation=generation), tempfile.TemporaryDirectory() as tmp:
                    root = Path(tmp)
                    config = root / filename
                    config.parent.mkdir(parents=True, exist_ok=True)
                    config.write_text(f'KMI_GENERATION = "{generation}" # source value\n')
                    result = self.resolve(root)
                    self.assertEqual(result.returncode, 0, result.stderr)
                    self.assertEqual(result.stdout.strip(), str(generation))

    def test_missing_invalid_and_conflicting_values_fail(self):
        for contents in ({}, {"build.config.constants": "KMI_GENERATION=$(echo 6)\n"},
                         {"build.config.constants": "KMI_GENERATION=6\n",
                          "build.config.common": "KMI_GENERATION=5\n"}):
            with self.subTest(contents=contents), tempfile.TemporaryDirectory() as tmp:
                root = Path(tmp)
                for filename, content in contents.items():
                    (root / filename).write_text(content)
                result = self.resolve(root)
                self.assertNotEqual(result.returncode, 0)
                self.assertIn("KMI_GENERATION", result.stderr)
                self.assertEqual(result.stdout, "")

    def test_workflow_suffixes_follow_source(self):
        workflows = ROOT / ".github/workflows"
        for filename in ("build.yml", "build-make.yml", "Build Kernel OnePlus.yml",
                         "build-kernel-original-make.yml"):
            path = workflows / filename
            if not path.exists():
                continue
            workflow = yaml.safe_load(path.read_text(encoding="utf-8"))
            steps = next(iter(workflow["jobs"].values()))["steps"]
            for step in steps:
                run = step.get("run", "")
                if filename in ("build.yml", "build-make.yml"):
                    if 'case "${{ inputs.kernel_version }}" in' not in run:
                        continue
                    run = re.search(r'case "\$\{\{ inputs.kernel_version \}\}" in.*?esac',
                                    run, re.S).group()
                    output = "KERNEL_LOCAL"
                elif step.get("name") in ("Custom Kernel Suffix if set", "Custom Kernel Random Suffix if empty"):
                    if filename == "Build Kernel OnePlus.yml" and "if set" in step["name"]:
                        continue  # Explicit user suffixes are not generated by this step.
                    run = run.split("for path in", 1)[0]
                    output = "VERSION_SUFFIX" if "if set" in step["name"] else "RANDOM_SUFFIX"
                else:
                    continue
                for generation in (5, 6, 7, None):
                    with self.subTest(file=filename, step=step["name"], generation=generation), tempfile.TemporaryDirectory() as tmp:
                        root = Path(tmp)
                        common = root / "kernel_workspace/kernel_platform/common"
                        common.mkdir(parents=True)
                        if generation is not None:
                            (common / "build.config.constants").write_text(f"KMI_GENERATION={generation}\n")
                        replacements = {"inputs.kernel_version": "6.12", "inputs.android_version": "android16",
                                        "env.KERNEL_VERSION": "6.12", "env.KANDROID_VERSION": "android16",
                                        "inputs.FAST_BUILD": "true", "inputs.SUFFIX": "custom"}
                        code = run
                        for key, value in replacements.items():
                            code = code.replace("${{ " + key + " }}", value)
                        # Use the test interpreter even when Git Bash cannot resolve python3.
                        code = code.replace("python3 ", '"$TEST_PYTHON" ')
                        code += '\nprintf "SUFFIX_RESULT=%s\\n" "$' + output + '"\n'
                        env = dict(os.environ, GITHUB_WORKSPACE=ROOT.as_posix(),
                                   KERNEL_ROOT=common.parent.as_posix(),
                                   GHASH="abcdef0123456", TEST_PYTHON=Path(sys.executable).as_posix())
                        result = subprocess.run([BASH, "-e", "-c", code], cwd=root,
                                                env=env, capture_output=True, text=True)
                        if generation is None:
                            self.assertNotEqual(result.returncode, 0)
                            self.assertIn("KMI_GENERATION", result.stderr)
                            self.assertNotIn("SUFFIX_RESULT=", result.stdout)
                        else:
                            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
                            suffix = result.stdout.split("SUFFIX_RESULT=", 1)[1].strip()
                            prefix = "-android16-" if output == "KERNEL_LOCAL" else ""
                            self.assertTrue(suffix.startswith(f"{prefix}{generation}-"), suffix)


if __name__ == "__main__":
    unittest.main()
